<?php

namespace Views;

use CodeIgniter\HTTP\RequestInterface;
use CodeIgniter\HTTP\ResponseInterface;
use Config\Services;
use Models\CustomFileModel;
use Models\SettingModel;
use Psr\Log\LoggerInterface;

class BaseClientController extends BaseViewController
{
    protected SettingModel $settingModel;
    protected CustomFileModel $customFileModel;
    /**
     * to check login when user access page automatically
     * @var bool
     */
    protected bool $isCheckLogin = false;

    public function __construct()
    {
        $this->settingModel = model('Models\SettingModel');
        $this->customFileModel = model('Models\CustomFileModel');
    }

    public function initController(RequestInterface $request, ResponseInterface $response, LoggerInterface $logger)
    {
        parent::initController($request, $response, $logger); // TODO: Change the autogenerated stub
        $this->setLanguage();
        if ($this->isCheckLogin) {
            $this->checkLogin();
        }
    }

    /**
     * login 상태일 때 페이지에 대한 접근 체크 기능
     * @return void
     */
    protected function checkLogin(): void
    {
        if ($this->session->is_login) {
            $response = Services::response();
            $response->setBody(view('/redirect', [
                'path' => '/profile',
            ]));
            $response->sendBody();
            exit;
        }
    }

    /**
     * logout 상태일 때 페이지에 대한 접근 체크 기능
     * @return void
     */
    protected function checkLogout(): void
    {
        if (!$this->session->is_login) {
            $response = Services::response();
            $response->setBody(view('/redirect', [
                'path' => '/',
            ]));
            $response->sendBody();
            exit;
        }
    }

    /**
     * 공통 header 부분 출력 기능
     * @param array $data
     * @param array $initData
     * @return string
     */
    protected function loadHeader(array $data, array $initData = []): string
    {
        $logos = $this->customFileModel->getLogos();
        $initData = array_merge($initData, [
            'logos' => $logos,
        ]);
        return view('/client/header', parent::loadDataForHeader($data, $initData));
    }

    /**
     * 공통 footer 부분 출력 기능
     * @return string
     */
    protected function loadFooter(): string
    {
        return view('/client/footer');
    }

    /**
     * body 출력 시에 공통적으로 load 될 데이터 호출 기능
     * @return array
     */
    protected function getViewData(): array
    {
        $settings = [];
        $settingResult = $this->settingModel->get();
        foreach ($settingResult as $item) {
            $settings[$item['code']] = $item['value'];
        }

        return array_merge(parent::getViewData(), [
            // todo translation
            'company_info' => [
                'name' => lang('Client.company_info_name'),
                'ceo_name' => lang('Client.company_info_ceo_name'),
                'cs_center' => lang('Client.company_info_cs_center'),
                'company_number' => lang('Client.company_info_company_number'),
                'certification_number' => lang('Client.company_info_certification_number'),
                'address' => lang('Client.company_info_address'),
                'email' => lang('Client.company_info_email'),
                'manager_name' => lang('Client.company_info_manager_name'),
            ],
            'terms' => [
                lang('Client.terms_01'),
                lang('Client.terms_02'),
            ],
            'settings' => $settings,
            'is_admin_page' => false,
        ]);
    }
}
